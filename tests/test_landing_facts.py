"""Every fact on the landing page, checked against the thing it describes.

The landing page's whole promise is that Sabi's citations are real. v1 typed
its hero examples into a template by hand, and two of its four citations
pointed at the wrong syllabus section: `PHY C2` is thermal expansion, not
motion, and `CHM A4` is the periodic table, not the mole. Its locator ticker
called `SYL D1` "Mensuration" when it is angles, triangles and polygons.
Nobody saw any of it, because nothing checked.

So the page's facts live in `web/content/landing.json`, and this file holds
each one to its source: the corpus documents, the eval set, the exam format
configs, and the refusal code itself. No database: these are all files.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import pytest
import yaml

ROOT = Path(__file__).resolve().parent.parent
LANDING = json.loads((ROOT / "web" / "content" / "landing.json").read_text(encoding="utf-8"))
CORPUS = ROOT / "corpus"


def _squash(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def _documents() -> dict[str, dict]:
    """locator -> {title, body, subject, kind}, read from front matter."""
    docs: dict[str, dict] = {}
    for path in CORPUS.rglob("*.md"):
        text = path.read_text(encoding="utf-8")
        match = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.DOTALL)
        assert match, f"{path} has no front matter"
        front = yaml.safe_load(match.group(1))
        docs[front["locator"]] = {
            "title": front["title"],
            "body": _squash(match.group(2)),
            "subject": front.get("subject", "Mathematics"),
            "kind": front.get("attribution"),
            "path": path,
        }
    return docs


DOCS = _documents()


# ------------------------------------------------------------------- the deck


@pytest.mark.parametrize("card", LANDING["deck"], ids=lambda c: c["source"]["locator"])
def test_every_hero_citation_points_at_the_section_it_claims(card):
    source = card["source"]
    doc = DOCS.get(source["locator"])
    assert doc is not None, f"{source['locator']} is not a locator in the corpus"
    assert source["title"] == doc["title"], (
        f"{source['locator']} is titled {doc['title']!r}, not {source['title']!r}"
    )


@pytest.mark.parametrize("card", LANDING["deck"], ids=lambda c: c["source"]["locator"])
def test_every_quoted_passage_is_verbatim_from_that_document(card):
    """The underlined sentence, and what sits either side of it, must be the
    document's own words in its own order -- the page shows them as a quote."""
    source = card["source"]
    quoted = _squash(" ".join(p for p in (source["before"], source["cited"], source["after"]) if p))
    assert quoted in DOCS[source["locator"]]["body"], (
        f"the passage shown for {source['locator']} is not in that document:\n{quoted}"
    )


def test_the_refusal_card_is_what_sabi_actually_says():
    """Generated by the product's own refusal code, not written for the page.

    If the refusal wording changes, this card must change with it -- a landing
    page showing a refusal the product no longer gives is a small lie."""
    from sabi.answer import refusals
    from sabi.answer.voice import voice_for
    from sabi.retrieval.scope import RetrievalScope

    card = next(c for c in LANDING["deck"] if "refusal" in c)
    doc = DOCS[card["source"]["locator"]]
    exclusion = doc["body"].split("## Not on this syllabus", 1)[1]

    said = refusals.out_of_syllabus(
        None,
        exclusion,
        card["source"]["locator"],
        [],
        voice_for(RetrievalScope("Mathematics", "WAEC")),
    )
    assert said.text == card["refusal"]


def test_the_worked_answers_are_arithmetically_right():
    """Checked by computing them, not by reading them."""
    # 2x^2 + 5x - 3 = 0 has roots 0.5 and -3.
    for x in (0.5, -3):
        assert 2 * x * x + 5 * x - 3 == 0
    assert (2.5 / 2) ** 2 == 1.5625 and 1.5 + 1.5625 == 3.0625 and 3.0625 ** 0.5 == 1.75
    # From rest to 20 m/s in 8 s.
    a = (20 - 0) / 8
    assert a == 2.5 and 0.5 * a * 8**2 == 80
    # 8 g of O2.
    assert 8 / (2 * 16) == 0.25


# ----------------------------------------------------------------- the ticker


@pytest.mark.parametrize("item", LANDING["ticker"], ids=lambda i: i[0])
def test_every_ticker_locator_carries_its_real_title(item):
    locator, title = item
    assert locator in DOCS, f"{locator} is not in the corpus"
    assert DOCS[locator]["title"] == title, (
        f"{locator} is {DOCS[locator]['title']!r}, not {title!r}"
    )


# ---------------------------------------------------------------- the figures


def test_the_headline_figures_are_counted_not_remembered():
    figures = LANDING["figures"]
    syllabus = sum(1 for d in DOCS.values() if d["kind"] == "syllabus")
    examples = len(DOCS) - syllabus
    golden = sum(
        1
        for path in (ROOT / "eval" / "golden").glob("*.jsonl")
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip().startswith("{")
    )
    assert figures["syllabus_documents"] == syllabus
    assert figures["worked_examples"] == examples
    assert figures["test_questions"] == golden


def test_the_subject_counts_are_the_corpus():
    by_subject: dict[str, int] = {}
    for doc in DOCS.values():
        by_subject[doc["subject"]] = by_subject.get(doc["subject"], 0) + 1

    configured = yaml.safe_load((ROOT / "config" / "limits.yaml").read_text(encoding="utf-8"))
    live = set(configured["syllabus"]["subjects"])

    for subject in LANDING["subjects"]:
        key = "Mathematics" if subject["name"] == "Core Mathematics" else subject["name"]
        assert subject["documents"] == by_subject.get(key, 0), subject["name"]
        # "Live" on the page means switched on in retrieval, not merely written.
        assert subject["live"] == (key in live), subject["name"]


# ------------------------------------------------------------------ the exams


def test_the_jamb_line_matches_its_verified_config():
    jamb = next(e for e in LANDING["exams"] if e["key"] == "jamb_utme")
    config = yaml.safe_load((ROOT / "exam_formats" / "jamb_utme.yaml").read_text(encoding="utf-8"))

    questions = sum(s["question_count"] for s in config["sections"])
    hours = config["total_duration_minutes"] / 60
    subjects = config["subject_rules"]["min_subjects"]

    assert f"{questions} questions" in jamb["shape"]
    assert f"{hours:g} hours" in jamb["shape"]
    assert f"out of {config['scoring']['scale_max']}" in jamb["shape"]
    assert f"{subjects} subjects" in jamb["shape"]


def test_no_exam_is_called_ready_without_a_config_behind_it():
    formats = {p.stem for p in (ROOT / "exam_formats").glob("*.yaml")}
    for exam in LANDING["exams"]:
        if exam["ready"]:
            assert exam["key"] in formats, f"{exam['name']} is marked ready with no config"
